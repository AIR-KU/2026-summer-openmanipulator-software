"""치수와 규약 상수.

수치를 고칠 일이 있으면 **이 파일만** 만지면 된다.
수식 자체는 kinematics.py 에 있고, 여기 값을 그대로 받아 쓴다.

세 종류가 섞여 있으니 구분해서 볼 것.
  (1) URDF 에서 읽은 값   — 로봇이 바뀌지 않는 한 고정
  (2) 실측이 필요한 값     — 펜 홀더를 만들 때마다 자로 재서 바꾼다
  (3) 팀 규약 값           — 각도를 어느 방향으로 셀지 정한 약속
"""

from math import atan2, hypot, pi

# ══════════════════════════════════════════════════════════════
#  (1) URDF 에서 읽은 값  [m]
#      open_manipulator_robot.urdf 의 <origin xyz="..."> 와 1:1 대응
# ══════════════════════════════════════════════════════════════

L1 = 0.0765   # 바닥 -> 어깨(joint2).  joint1.z(0.017) + joint2.z(0.0595)
A_OFF = 0.024  # link2 옆 꺾임.        joint3 origin 의 x
B_OFF = 0.128  # link2 위 길이.        joint3 origin 의 z
L3 = 0.124     # 팔꿈치 -> 손목.       joint4 origin 의 x

# joint1 origin 의 x. 어깨 기둥이 베이스 중심축에서 이만큼 앞으로 나가 있다.
# 회전축(z)에 실려 도는 값이 아니라 베이스 프레임에 고정된 오프셋이다.
X_OFF = 0.012

# ══════════════════════════════════════════════════════════════
#  (2) 실측이 필요한 값  [m]   ★ 홀더를 바꾸면 반드시 다시 잰다
#      집게에 펜이 직각으로 물린 형태라 성분이 두 개다.
# ══════════════════════════════════════════════════════════════

P_LEN = 0.110  # 손목 -> 펜 축.    링크가 뻗은 방향
E_LEN = 0.045  # 링크 축 -> 펜 끝.  링크에 직각인 방향

# ══════════════════════════════════════════════════════════════
#  (3) 팀 규약 값
# ══════════════════════════════════════════════════════════════

# theta1 = 0 일 때 팔이 +y(12시)를 향한다는 약속.
# 그래서 PyBullet 에 로봇을 놓을 때 z축으로 +90도 돌려 놓고(BASE_YAW),
# IK 는 월드 방위 atan2(y, x) 에서 그만큼 빼서 관절값을 만든다.
# 이 둘은 항상 부호가 반대여야 한다.
BASE_YAW = pi / 2      # PyBullet 배치 회전
TH1_SIGN = +1.0        # theta1 회전 방향 (+1 또는 -1)
TH1_OFFSET = -BASE_YAW  # = -pi/2

# theta2~4 를 기하각(psi)에서 관절각으로 옮길 때의 부호.
# 팀 규약이 안쪽 방향이면 -1, URDF 방향 그대로면 +1.
SIGN_234 = -1.0

# 공구 자세각. link5 가 수평일 때 펜이 수직으로 서므로 0.
PHI = 0.0

# 팔꿈치 분기. 한 궤적 안에서는 반드시 하나로 통일해야
# 중간에 팔이 뒤집히지 않는다.
ELBOW_UP = True

# ══════════════════════════════════════════════════════════════
#  파생 상수 — 위 값에서 자동 계산된다. 직접 고치지 말 것.
# ══════════════════════════════════════════════════════════════

L2 = hypot(A_OFF, B_OFF)   # 꺾인 링크의 대각선 길이  = 0.13023 m
BETA = atan2(A_OFF, B_OFF)  # 꺾인 각도                = 10.62 deg
OFF = pi / 2 - BETA         # 영점 자세 오프셋          = 79.38 deg

# ══════════════════════════════════════════════════════════════
#  제약 스위치 — 관절 제한을 URDF 보다 넓히거나 좁힌다.
#  자세한 배경은 README 의 "제약조건" 절 참고.
# ══════════════════════════════════════════════════════════════

# URDF 의 joint1 은 +-162도라 324도만 돈다. 그래서 로봇 정반대 방향에
# 36도 폭의 사각지대가 생긴다. 실물이 한 바퀴 도는 것을 확인했다면
# True 로 두어 +-180도로 넓힌다.
JOINT1_FULL_TURN = False

# theta2 추가 제약: 상완(어깨->팔꿈치)이 수직을 넘어 뒤로 젖혀지지 않게.
#   상완각 = (90도 - BETA) - theta2   이므로
#   theta2 = -BETA  -> 상완이 정확히 수직
#   theta2 < -BETA  -> 수직을 넘어 뒤로 꺾임
# URDF 하한 -1.7907(-102.6도)을 그대로 쓰면 팔이 뒤로 넘어간다.
# 종이 위(z=0) 작업 영역은 이 제약을 걸어도 줄지 않는다.
NO_BACKWARD_ARM = False

# X_OFF(12mm)를 보정할지.  ★ 실물 검증 전까지 기본 False
#
# False 로 두면 어깨가 베이스 중심축 위에 있다고 보고 푼다. 그러면 FK 로
# 되짚은 펜 끝이 목표점보다 월드 +y 로 정확히 12mm 밀린다. 목표점이
# 어디든 크기와 방향이 같은 순수 평행이동 오차다.
#   -> scripts/ik_verify.py 의 검사 C 에서 실제 수치를 볼 수 있다.
#
# True 로 두면 목표점에서 이 오프셋을 먼저 빼고 푼다. 시뮬레이터 기준
# 오차는 12mm -> 0mm 가 된다. 실물에서도 맞는지 확인한 뒤 켤 것.
APPLY_X_OFFSET = False

# ══════════════════════════════════════════════════════════════
#  장면 설정 — 궤적을 만들 때 쓰는 높이
# ══════════════════════════════════════════════════════════════

Z_PAPER = 0.0   # 종이 표면 높이 (펜 끝 기준)
Z_UP = 0.05     # 펜을 든 높이

# 시작 자세. +y(12시) 방향이고 팔이 뒤로 꺾이지 않는 곳이어야 한다.
# 가깝고 높은 자리(예: r=0.15, z=0.12)는 상완각이 130도까지 올라가 젖혀진다.
HOME = (0.0, 0.24, 0.12)
